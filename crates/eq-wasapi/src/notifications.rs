//! Device notifications through `IMMNotificationClient`, forwarded as [`DeviceEvent`]s.

#![allow(
    clippy::inline_always,
    clippy::borrow_as_ptr,
    clippy::ref_as_ptr,
    reason = "generated by the `#[implement]` macro, which is outside this crate"
)]

use crossbeam_channel::Sender;
use eq_core::{DeviceEvent, DeviceId};
use windows::Win32::Foundation::PROPERTYKEY;
use windows::Win32::Media::Audio::{
    DEVICE_STATE, DEVICE_STATE_ACTIVE, EDataFlow, ERole, IMMDeviceEnumerator,
    IMMNotificationClient, IMMNotificationClient_Impl, eConsole, eRender,
};
use windows::core::{PCWSTR, Result as WinResult, implement};

use crate::error::{ComResultExt, WasapiError};

/// The COM object that Windows calls back on device changes.
///
/// Callbacks run on COM worker threads and must not block. Each one converts its arguments into
/// a [`DeviceEvent`] and sends it on an unbounded channel, which never blocks the sender.
#[implement(IMMNotificationClient)]
struct NotificationClient {
    tx: Sender<DeviceEvent>,
}

impl NotificationClient {
    /// Sends `event`, ignoring the error when the receiver has been dropped.
    fn send(&self, event: DeviceEvent) {
        // The receiver is gone only during shutdown; there is nothing useful to do then.
        let _ = self.tx.send(event);
    }
}

/// Copies the device id from a callback argument.
///
/// Returns `None` for a null pointer. Invalid UTF-16 is replaced, not dropped.
fn copy_id(id: PCWSTR) -> Option<DeviceId> {
    if id.is_null() {
        return None;
    }
    // SAFETY: Windows passes a NUL-terminated string that stays valid until the callback returns.
    // The string is copied before the callback returns.
    let text = String::from_utf16_lossy(unsafe { id.as_wide() });
    Some(DeviceId::new(text))
}

impl IMMNotificationClient_Impl for NotificationClient_Impl {
    fn OnDeviceStateChanged(
        &self,
        pwstrdeviceid: &PCWSTR,
        dwnewstate: DEVICE_STATE,
    ) -> WinResult<()> {
        if let Some(id) = copy_id(*pwstrdeviceid) {
            if dwnewstate == DEVICE_STATE_ACTIVE {
                self.send(DeviceEvent::Added(id));
            } else {
                self.send(DeviceEvent::Removed(id));
            }
        }
        Ok(())
    }

    fn OnDeviceAdded(&self, pwstrdeviceid: &PCWSTR) -> WinResult<()> {
        if let Some(id) = copy_id(*pwstrdeviceid) {
            self.send(DeviceEvent::Added(id));
        }
        Ok(())
    }

    fn OnDeviceRemoved(&self, pwstrdeviceid: &PCWSTR) -> WinResult<()> {
        if let Some(id) = copy_id(*pwstrdeviceid) {
            self.send(DeviceEvent::Removed(id));
        }
        Ok(())
    }

    fn OnDefaultDeviceChanged(
        &self,
        flow: EDataFlow,
        role: ERole,
        pwstrdefaultdeviceid: &PCWSTR,
    ) -> WinResult<()> {
        // Only the console render default matters: the controller routes through that role.
        // Windows sends one callback per role, and a null id means no default exists.
        if flow == eRender
            && role == eConsole
            && let Some(id) = copy_id(*pwstrdefaultdeviceid)
        {
            self.send(DeviceEvent::DefaultChanged(id));
        }
        Ok(())
    }

    fn OnPropertyValueChanged(&self, _pwstrdeviceid: &PCWSTR, _key: &PROPERTYKEY) -> WinResult<()> {
        // Property changes are not part of the device events.
        Ok(())
    }
}

/// Keeps a device-notification client registered with the enumerator.
///
/// Registration ends when the guard is dropped. Windows calls the client on COM worker threads.
/// The guard itself must be dropped on the thread that created the enumerator, so it is neither
/// `Send` nor `Sync`.
///
/// Added and removed events carry no data-flow information, so capture devices produce events
/// too. The controller ignores ids that are not in its render list.
pub struct NotificationGuard {
    enumerator: IMMDeviceEnumerator,
    client: IMMNotificationClient,
}

impl NotificationGuard {
    /// Registers a client that sends every device event on `tx`.
    ///
    /// # Errors
    ///
    /// Returns [`WasapiError::Com`] when Windows rejects the registration.
    pub fn register(
        enumerator: &IMMDeviceEnumerator,
        tx: Sender<DeviceEvent>,
    ) -> Result<Self, WasapiError> {
        let client: IMMNotificationClient = NotificationClient { tx }.into();
        // SAFETY: the enumerator and the client are live COM objects on this thread. The guard
        // keeps the client alive, and `Drop` unregisters it before releasing the client.
        unsafe { enumerator.RegisterEndpointNotificationCallback(&client) }
            .context("IMMDeviceEnumerator::RegisterEndpointNotificationCallback")?;
        Ok(Self {
            enumerator: enumerator.clone(),
            client,
        })
    }
}

impl Drop for NotificationGuard {
    fn drop(&mut self) {
        // SAFETY: this client was registered with this enumerator on this thread in `register`.
        // The result is ignored because a destructor cannot report it.
        let _ = unsafe {
            self.enumerator
                .UnregisterEndpointNotificationCallback(&self.client)
        };
    }
}
