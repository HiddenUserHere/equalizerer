//! Changes the default audio output through the undocumented `IPolicyConfig` COM interface.
//!
//! The interfaces below are declared to match the vtable layout that Windows ships. The
//! method order is part of the binary contract: the slot order must not change, and every method
//! must be declared even when it is unused. Only `SetDefaultEndpoint` is called.

#![allow(
    non_snake_case,
    clippy::transmute_ptr_to_ptr,
    reason = "the method names must match Windows; the transmute is generated by #[interface]"
)]

use std::ffi::c_void;

use eq_core::{BackendError, DeviceId, EndpointDirectory};
use windows::Win32::Media::Audio::{ERole, eConsole, eMultimedia};
use windows::Win32::System::Com::{CLSCTX_ALL, CoCreateInstance};
use windows::core::{GUID, HRESULT, IUnknown, IUnknown_Vtbl, Interface, PCWSTR, interface};

use crate::error::{ComResultExt, HRESULT_NOT_FOUND, WasapiError};

/// Class id of the policy config client (`CPolicyConfigClient`).
const CLSID_POLICY_CONFIG_CLIENT: GUID = GUID::from_u128(0x870af99c_171d_4f9e_af0d_e63df40c2bc9);

/// `IPolicyConfig` as shipped with Windows 10 and later, vtable order fixed by Windows.
///
/// Parameters the backend never passes are raw pointers; they keep the slot layout exact.
#[interface("F8679F50-850A-41CF-9C72-430F290290C8")]
pub unsafe trait IPolicyConfig: IUnknown {
    /// Slot 0: returns the shared-mode format of a device.
    fn GetMixFormat(&self, device_id: PCWSTR, format: *mut *mut c_void) -> HRESULT;
    /// Slot 1: returns the device or default format.
    fn GetDeviceFormat(&self, device_id: PCWSTR, default: i32, format: *mut *mut c_void)
    -> HRESULT;
    /// Slot 2: resets a device format to its default.
    fn ResetDeviceFormat(&self, device_id: PCWSTR) -> HRESULT;
    /// Slot 3: sets the device format.
    fn SetDeviceFormat(
        &self,
        device_id: PCWSTR,
        endpoint_format: *mut c_void,
        mix_format: *mut c_void,
    ) -> HRESULT;
    /// Slot 4: reads the processing periods.
    fn GetProcessingPeriod(
        &self,
        device_id: PCWSTR,
        default: i32,
        default_period: *mut i64,
        minimum_period: *mut i64,
    ) -> HRESULT;
    /// Slot 5: sets the processing period.
    fn SetProcessingPeriod(&self, device_id: PCWSTR, period: *mut i64) -> HRESULT;
    /// Slot 6: reads the share mode.
    fn GetShareMode(&self, device_id: PCWSTR, mode: *mut c_void) -> HRESULT;
    /// Slot 7: sets the share mode.
    fn SetShareMode(&self, device_id: PCWSTR, mode: *mut c_void) -> HRESULT;
    /// Slot 8: reads a device property.
    fn GetPropertyValue(
        &self,
        device_id: PCWSTR,
        key: *const c_void,
        value: *mut c_void,
    ) -> HRESULT;
    /// Slot 9: writes a device property.
    fn SetPropertyValue(
        &self,
        device_id: PCWSTR,
        key: *const c_void,
        value: *mut c_void,
    ) -> HRESULT;
    /// Slot 10: makes the device the default for `role`.
    fn SetDefaultEndpoint(&self, device_id: PCWSTR, role: ERole) -> HRESULT;
    /// Slot 11: shows or hides the device in the sound settings.
    fn SetEndpointVisibility(&self, device_id: PCWSTR, visible: i32) -> HRESULT;
}

