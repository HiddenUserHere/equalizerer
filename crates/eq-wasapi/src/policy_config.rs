/// Either policy interface, whichever the running Windows provides.
enum PolicyConfig {
    Current(IPolicyConfig),
    Vista(IPolicyConfigVista),
}

impl PolicyConfig {
    /// Calls `SetDefaultEndpoint` on the wrapped interface.
    fn set_default_endpoint(&self, device_id: PCWSTR, role: ERole) -> HRESULT {
        match self {
            // SAFETY: the wrapped interface pointer is live for as long as `self` is. The caller
            // keeps `device_id` NUL-terminated and alive for the duration of the call.
            Self::Current(policy) => unsafe { policy.SetDefaultEndpoint(device_id, role) },
            // SAFETY: same as above, for the Vista interface.
            Self::Vista(policy) => unsafe { policy.SetDefaultEndpoint(device_id, role) },
        }
    }
}

/// Makes `id` the default output for the console and multimedia roles.
///
/// The communications role is deliberately left unchanged. The policy client is created on
/// each call and released before returning.
///
/// # Errors
///
/// Returns [`WasapiError::DeviceNotFound`] when Windows does not know `id`, and
/// [`WasapiError::Com`] when the policy client cannot be created or rejects the change.
pub(crate) fn set_default_endpoint(id: &DeviceId) -> Result<(), WasapiError> {
    // SAFETY: the class id is a valid static GUID, the outer object is null and the class does
    // not aggregate. The result is checked by `?`.
    let client: IUnknown =
        unsafe { CoCreateInstance(&CLSID_POLICY_CONFIG_CLIENT, None, CLSCTX_ALL) }
            .context("CoCreateInstance(CPolicyConfigClient)")?;
    let policy = match client.cast::<IPolicyConfig>() {
        Ok(policy) => PolicyConfig::Current(policy),
        Err(_) => PolicyConfig::Vista(
            client
                .cast::<IPolicyConfigVista>()
                .context("QueryInterface(IPolicyConfigVista)")?,
        ),
    };

    // NUL-terminated copy of the id; it lives until the end of this function, which covers every
    // call below.
    let wide: Vec<u16> = id
        .as_str()
        .encode_utf16()
        .chain(std::iter::once(0))
        .collect();
    let device_id = PCWSTR::from_raw(wide.as_ptr());

    for role in [eConsole, eMultimedia] {
        let hr = policy.set_default_endpoint(device_id, role);
        if hr == HRESULT_NOT_FOUND {
            return Err(WasapiError::DeviceNotFound(id.to_string()));
        }
        hr.ok().context("IPolicyConfig::SetDefaultEndpoint")?;
    }
    Ok(())
}

/// Sets a default output on creation and restores the previous one when dropped.
///
/// Create it before changing the default, then keep it alive for as long as the change should
/// last. On drop it makes the previous default current again. Errors are ignored, since a
/// destructor cannot report them. If no default existed at creation, dropping does nothing.
///
/// Dropping does not run on a hard kill (for example, Ctrl+C with the default handler), so the
/// application must also restore the default on its own shutdown path.
pub struct RestoreDefaultGuard<'a> {
    directory: &'a dyn EndpointDirectory,
    previous: Option<DeviceId>,
}

impl<'a> RestoreDefaultGuard<'a> {
    /// Records the current default output of `directory`.
    ///
    /// # Errors
    ///
    /// Returns [`BackendError`] when the current default cannot be read.
    pub fn new(directory: &'a dyn EndpointDirectory) -> Result<Self, BackendError> {
        let previous = directory.default_render()?;
        Ok(Self {
            directory,
            previous,
        })
    }

    /// Returns the default output recorded at creation, if one existed.
    #[must_use]
    pub fn previous(&self) -> Option<&DeviceId> {
        self.previous.as_ref()
    }
}

impl Drop for RestoreDefaultGuard<'_> {
    fn drop(&mut self) {
        if let Some(previous) = &self.previous {
            // Errors are ignored: a destructor has no channel to report them.
            let _ = self.directory.set_default_render(previous);
        }
    }
}
