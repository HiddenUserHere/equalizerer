/// How long an error toast stays on screen.
const TOAST_DURATION: Duration = Duration::from_secs(4);

/// Width of the curve area before the window reports its real size, in logical px.
const DEFAULT_PLOT_WIDTH: f32 = 1_000.0;

/// Height of the curve area, in logical px. It matches the slider track height on the Slint side.
const DEFAULT_PLOT_HEIGHT: f32 = 180.0;

/// Gain range shown on the plot, in dB above and below 0 dB.
const CURVE_DB_RANGE: f32 = eq_dsp::GAIN_MAX_DB;

thread_local! {
    /// State that only the UI thread touches: timers, the curve inputs and the presets.
    static UI_STATE: RefCell<UiState> = RefCell::new(UiState {
        plot_size: (DEFAULT_PLOT_WIDTH, DEFAULT_PLOT_HEIGHT),
        ..UiState::default()
    });
}

/// Inputs of the curve paths: the gains and the curve area size they were computed for.
type CurveKey = (Vec<f32>, (f32, f32));

/// UI-thread-only state, kept in a thread local because `slint::Timer` is not `Send`.
#[derive(Default)]
struct UiState {
    /// Hides the error toast. Restarting it replaces the pending hide, so a newer error stays
    /// visible for the full duration.
    toast_timer: Timer,
    /// Gains from the last snapshot. Empty until the first snapshot arrives.
    curve_gains: Vec<f32>,
    /// Size of the curve area in logical px, from the last `curve-resized` report.
    plot_size: (f32, f32),
    /// Inputs the curve paths on screen were computed from, to skip recomputation.
    curve_drawn: Option<CurveKey>,
    /// Output devices from the last snapshot. Dropdown entries are looked up here by index.
    devices: Vec<DeviceInfo>,
    /// Presets from the last snapshot, used to validate dialog names.
    presets: Vec<PresetSummary>,
    /// Active preset from the last snapshot.
    active_preset: Option<String>,
    /// Latency mode from the last snapshot.
    latency: LatencyMode,
    /// Whether audio is routed. The latency label shows a value only then.
    routing: bool,
    /// Decides when the dropout hint is shown.
    underruns: UnderrunMonitor,
    /// The dialog that is open, if any.
    dialog: Option<DialogKind>,
    /// Whether the controller has been sent `AppCommand::Quit`. The window can ask for a quit from
    /// the close button and from the tray menu, but the controller must get it only once.
    quit_sent: bool,
}

/// How the window starts and what the "Start with Windows" checkbox may change.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct UiOptions {
    /// Start with the window hidden. This needs a tray icon to bring the window back; without
    /// one the window is shown anyway.
    pub start_minimized: bool,
    /// Whether the checkbox writes the autostart setting. Demo mode shows the checkbox but must
    /// not change the user's startup settings.
    pub persist_autostart: bool,
}

/// Creates the main window and runs it until the user quits.
///
/// UI actions are sent to `commands`. Events from the controller are read from `events` on a
/// forwarder thread and applied on the UI thread. Each message on `show_requests` (a second app
/// instance asked for the window) shows the window. Where the platform has a tray icon, it offers
/// "Open Equalizerer" and "Quit". Minimizing the window hides it to the tray; closing it quits,
/// like the tray's "Quit".
///
/// The event loop keeps running while the window is hidden, so the function returns only through
/// a quit. A quit sends [`AppCommand::Quit`] once and stops the loop.
///
/// # Errors
///
/// Returns an error if the window cannot be created or the event loop fails. In that case
/// [`AppCommand::Quit`] is not sent; the caller must send it.
#[allow(
    clippy::needless_pass_by_value,
    clippy::too_many_lines,
    reason = "the channel ends are moved in by contract; the function owns the UI session and \
              wires one callback per control"
)]
pub fn run_ui(
    commands: Sender<AppCommand>,
    events: Receiver<AppEvent>,
    show_requests: Receiver<()>,
    options: UiOptions,
) -> Result<(), slint::PlatformError> {
    window::select_backend()?;
    let window = AppWindow::new()?;
    window.set_band_positions(model(eq_view::band_positions(Layout::Ten)));
    window.set_latency_labels(model(
        LatencyMode::ALL
            .iter()
            .map(|mode| SharedString::from(mode.label()))
            .collect(),
    ));
    window.set_autostart_available(backend::autostart_available());
    window.set_autostart_on(match backend::autostart_is_enabled() {
        Ok(enabled) => enabled,
        Err(error) => {
            tracing::warn!("cannot read the Start with Windows setting: {error}");
            false
        }
    });

    let power_commands = commands.clone();
    window.on_power_toggled(move |on| send(&power_commands, AppCommand::SetPower(on)));

    let gain_commands = commands.clone();
    window.on_gain_changed(move |band, db| {
        // A negative band index cannot come from the UI; ignore it rather than trust it.
        if let Ok(band) = usize::try_from(band) {
            send(&gain_commands, AppCommand::SetGain { band, db });
        }
    });

    let device_commands = commands.clone();
    window.on_device_selected(move |index| {
        // A negative index cannot come from the UI; ignore it rather than trust it.
        let Ok(index) = usize::try_from(index) else {
            return;
        };
        let target = UI_STATE.with(|state| devices_view::device_at(&state.borrow().devices, index));
        if let Some(id) = target {
            send(&device_commands, AppCommand::SelectTarget(id));
        }
    });

    let preset_commands = commands.clone();
    window.on_preset_selected(move |name| {
        send(&preset_commands, AppCommand::SelectPreset(name.to_string()));
    });

    let save_commands = commands.clone();
    window.on_preset_save(move || send(&save_commands, AppCommand::SavePreset));

    let weak = window.as_weak();
    window.on_preset_save_as(move || {
        if let Some(ui) = weak.upgrade() {
            open_dialog(&ui, DialogKind::SaveAs);
        }
    });

    let weak = window.as_weak();
    window.on_preset_rename(move || {
        if let (Some(ui), Some(from)) = (weak.upgrade(), selected_user_preset()) {
            open_dialog(&ui, DialogKind::Rename { from });
        }
    });

    let weak = window.as_weak();
    window.on_preset_delete(move || {
        if let (Some(ui), Some(name)) = (weak.upgrade(), selected_user_preset()) {
            open_dialog(&ui, DialogKind::Delete { name });
        }
    });

    let dialog_commands = commands.clone();
    let weak = window.as_weak();
    window.on_dialog_ok(move |text| {
        if let Some(ui) = weak.upgrade() {
            confirm_dialog(&ui, &dialog_commands, text.as_str());
        }
    });

    let weak = window.as_weak();
    window.on_dialog_cancel(move || {
        if let Some(ui) = weak.upgrade() {
            close_dialog(&ui);
        }
    });

    let weak = window.as_weak();
    window.on_dialog_edited(move |text| {
        if let Some(ui) = weak.upgrade() {
            update_dialog_check(&ui, text.as_str());
        }
    });

    let autostart_persist = options.persist_autostart;
    let weak = window.as_weak();
    window.on_autostart_toggled(move |enabled| {
        if let Some(ui) = weak.upgrade() {
            apply_autostart(&ui, enabled, autostart_persist);
        }
    });

    // The close button quits, like the tray's "Quit". The window itself is hidden as the event
    // loop ends.
    let close_commands = commands.clone();
    window.window().on_close_requested(move || {
        request_quit(&close_commands);
        CloseRequestResponse::HideWindow
    });

    let weak = window.as_weak();
    window.on_curve_resized(move |width, height| {
        // Sizes of 1 px or less come from layout passes before the plot has its size; NaN fails
        // the comparison too, so it is ignored as well.
        if !(width > 1.0 && height > 1.0) {
            return;
        }
        if let Some(ui) = weak.upgrade() {
            UI_STATE.with(|cell| cell.borrow_mut().plot_size = (width, height));
            update_curve(&ui);
        }
    });

    let latency_commands = commands.clone();
    window.on_latency_selected(move |index| {
        let Some(mode) = latency_view::mode_from_index(index) else {
            return;
        };
        // Changing the mode restarts the pipeline, so only a real change is sent.
        if mode != UI_STATE.with(|state| state.borrow().latency) {
            send(&latency_commands, AppCommand::SetLatency(mode));
        }
    });

    let weak = window.as_weak();
    std::thread::Builder::new()
        .name("ui-events".to_owned())
        .spawn(move || forward_events(&events, &weak))
        .map_err(|error| slint::PlatformError::Other(error.to_string()))?;

    let weak = window.as_weak();
    std::thread::Builder::new()
        .name("ui-show".to_owned())
        .spawn(move || forward_show_requests(&show_requests, &weak))
        .map_err(|error| slint::PlatformError::Other(error.to_string()))?;

    // A failed tray leaves no way to bring a hidden window back, so the window then keeps the
    // default behaviour: it is shown at start and minimizes normally.
    let (tray_tx, tray_rx) = unbounded::<TrayAction>();
    let tray = match tray::start(tray_tx) {
        Ok(tray) => tray,
        Err(message) => {
            tracing::warn!("{message}");
            None
        }
    };
    window::install_window_filter(&window, tray.is_some());
    let weak = window.as_weak();
    let tray_commands = commands.clone();
    std::thread::Builder::new()
        .name("ui-tray".to_owned())
        .spawn(move || forward_tray_actions(&tray_rx, &weak, &tray_commands))
        .map_err(|error| slint::PlatformError::Other(error.to_string()))?;

    let start_hidden = options.start_minimized && tray.is_some();
    if options.start_minimized && !start_hidden {
        tracing::info!("no tray icon is available; the window is shown at start");
    }
    if !start_hidden {
        window::show(&window);
    }

    // The loop keeps running while the window is hidden. It ends through `request_quit`.
    slint::run_event_loop_until_quit()?;

    // The tray icon disappears as soon as the loop has ended, not when the process exits.
    drop(tray);
    send_quit_once(&commands);
    Ok(())
}

/// Sends a command to the controller. A closed channel means the controller has stopped, and
/// there is nothing left for the UI to do about it.
fn send(commands: &Sender<AppCommand>, command: AppCommand) {
    let _ = commands.send(command);
}

/// Forwards controller events to the Slint event loop until either side goes away.
fn forward_events(events: &Receiver<AppEvent>, window: &slint::Weak<AppWindow>) {
    while let Ok(event) = events.recv() {
        let window = window.clone();
        let posted = slint::invoke_from_event_loop(move || {
            if let Some(ui) = window.upgrade() {
                apply_event(&ui, event);
            }
        });
        if posted.is_err() {
            // The event loop has ended, so the window is gone.
            break;
        }
    }
}

/// Shows the window for each show request until either side goes away.
fn forward_show_requests(requests: &Receiver<()>, window: &slint::Weak<AppWindow>) {
    while requests.recv().is_ok() {
        let window = window.clone();
        let posted = slint::invoke_from_event_loop(move || {
            if let Some(ui) = window.upgrade() {
                window::show(&ui);
            }
        });
        if posted.is_err() {
            // The event loop has ended, so the window is gone.
            break;
        }
    }
}

/// Applies tray requests on the UI thread until either side goes away. Open shows the window;
/// Quit runs the same shutdown as the close button.
fn forward_tray_actions(
    actions: &Receiver<TrayAction>,
    window: &slint::Weak<AppWindow>,
    commands: &Sender<AppCommand>,
) {
    while let Ok(action) = actions.recv() {
        let window = window.clone();
        let commands = commands.clone();
        let posted = slint::invoke_from_event_loop(move || match action {
            TrayAction::Open => {
                if let Some(ui) = window.upgrade() {
                    window::show(&ui);
                }
            }
            TrayAction::Quit => request_quit(&commands),
        });
        if posted.is_err() {
            // The event loop has ended, so the window is gone.
            break;
        }
    }
}

/// Sends `AppCommand::Quit` unless that was done already. Runs on the UI thread.
fn send_quit_once(commands: &Sender<AppCommand>) {
    let first = UI_STATE.with(|cell| !std::mem::replace(&mut cell.borrow_mut().quit_sent, true));
    if first {
        send(commands, AppCommand::Quit);
    }
}

/// Starts the shutdown: sends the quit once and stops the event loop, so `run_ui` returns.
/// Runs on the UI thread.
fn request_quit(commands: &Sender<AppCommand>) {
    send_quit_once(commands);
    if let Err(error) = slint::quit_event_loop() {
        tracing::warn!("cannot stop the event loop: {error}");
    }
}

/// Writes the "Start with Windows" setting and shows the outcome. When the write fails, the
/// checkbox goes back to its previous state. Runs on the UI thread.
fn apply_autostart(ui: &AppWindow, enabled: bool, persist: bool) {
    let result = if persist {
        backend::set_autostart(enabled)
    } else {
        Ok(())
    };
    match result {
        Ok(()) => ui.set_autostart_on(enabled),
        Err(message) => {
            show_error(
                ui,
                &format!("Start with Windows could not be changed: {message}"),
            );
            ui.set_autostart_on(!enabled);
        }
    }
}

/// Applies one controller event to the window. Runs on the UI thread.
fn apply_event(ui: &AppWindow, event: AppEvent) {
    match event {
        AppEvent::Snapshot(snapshot) => apply_snapshot(ui, &snapshot),
        AppEvent::Stats(stats) => apply_stats(ui, &stats),
        AppEvent::Error(message) => show_error(ui, &message),
    }
}

/// Copies a snapshot into the window properties.
fn apply_snapshot(ui: &AppWindow, snapshot: &AppSnapshot) {
    ui.set_power_on(snapshot.power);
    ui.set_status_text(SharedString::from(view_model::status_text(snapshot)));
    ui.set_status_degraded(view_model::status_is_degraded(snapshot.status));

    let target = snapshot.target_id.as_ref();
    ui.set_device_rows(model(
        devices_view::build_rows(&snapshot.devices, target)
            .into_iter()
            .map(device_row_item)
            .collect(),
    ));
    ui.set_device_label(SharedString::from(devices_view::selector_label(
        &snapshot.devices,
        target,
    )));
    ui.set_device_enabled(devices_view::is_enabled(&snapshot.devices));
    if let Some(gains) = sync_model(&ui.get_gains(), snapshot.gains.clone()) {
        ui.set_gains(gains);
    }
    let labels = view_model::gain_labels(&snapshot.gains)
        .into_iter()
        .map(SharedString::from)
        .collect();
    if let Some(labels) = sync_model(&ui.get_gain_labels(), labels) {
        ui.set_gain_labels(labels);
    }

    let active = snapshot.active_preset.as_deref();
    let actions = presets_view::actions(&snapshot.presets, active, snapshot.modified);
    ui.set_preset_rows(model(
        presets_view::build_rows(&snapshot.presets, active)
            .into_iter()
            .map(row_item)
            .collect(),
    ));
    ui.set_preset_label(SharedString::from(presets_view::selector_label(active)));
    ui.set_preset_modified(snapshot.modified && active.is_some());
    ui.set_can_save(actions.save);
    ui.set_can_rename(actions.rename);
    ui.set_can_delete(actions.delete);

    ui.set_latency_index(latency_view::mode_index(snapshot.latency));

    UI_STATE.with(|cell| {
        let mut state = cell.borrow_mut();
        state.devices.clone_from(&snapshot.devices);
        state.presets.clone_from(&snapshot.presets);
        state.active_preset.clone_from(&snapshot.active_preset);
        state.latency = snapshot.latency;
        state.routing = snapshot.status == RoutingStatus::On;
        state.underruns.set_mode(snapshot.latency);
        ui.set_dropout_hint(state.underruns.hint());
        if !state.routing {
            ui.set_latency_text(SharedString::from(latency_view::latency_text(None)));
        }

        state.curve_gains.clone_from(&snapshot.gains);
    });
    update_curve(ui);
}

/// Recomputes the curve paths and their viewbox when the gains or the curve area size changed.
///
/// The viewbox is set in the same call as the path commands, both for the same size, so the
/// curve always matches the sliders. Runs on the UI thread.
fn update_curve(ui: &AppWindow) {
    // The thread-local borrow ends before any Slint property is set.
    let Some((gains, (width, height))) = UI_STATE.with(|cell| {
        let mut state = cell.borrow_mut();
        if state.curve_gains.is_empty() {
            return None;
        }
        let key: CurveKey = (state.curve_gains.clone(), state.plot_size);
        if state.curve_drawn.as_ref() == Some(&key) {
            return None;
        }
        state.curve_drawn = Some(key.clone());
        Some(key)
    }) else {
        return;
    };

    ui.set_curve_viewbox_width(width);
    ui.set_curve_viewbox_height(height);
    ui.set_curve_fill(SharedString::from(eq_view::curve_path(
        &gains,
        width,
        height,
        CURVE_DB_RANGE,
    )));
    ui.set_curve_line(SharedString::from(eq_view::curve_line_path(
        &gains,
        width,
        height,
        CURVE_DB_RANGE,
    )));
}

/// Shows the measured latency and feeds the underrun counter to the dropout hint.
fn apply_stats(ui: &AppWindow, stats: &Stats) {
    UI_STATE.with(|cell| {
        let mut guard = cell.borrow_mut();
        let latency = guard.routing.then_some(stats.latency_ms);
        ui.set_latency_text(SharedString::from(latency_view::latency_text(latency)));
        ui.set_dropout_hint(guard.underruns.record(stats.underruns));
    });
}

/// Shows an error toast for [`TOAST_DURATION`].
fn show_error(ui: &AppWindow, message: &str) {
    ui.set_error_text(SharedString::from(message));
    ui.set_error_visible(true);

    let weak = ui.as_weak();
    UI_STATE.with(|state| {
        state
            .borrow()
            .toast_timer
            .start(TimerMode::SingleShot, TOAST_DURATION, move || {
                if let Some(ui) = weak.upgrade() {
                    ui.set_error_visible(false);
                }
            });
    });
}

/// Name of the active preset if it is a user preset; `None` for built-ins and "Custom".
fn selected_user_preset() -> Option<String> {
    UI_STATE.with(|state| {
        let state = state.borrow();
        let name = state.active_preset.as_ref()?;
        state
            .presets
            .iter()
            .any(|preset| preset.name == *name && !preset.builtin)
            .then(|| name.clone())
    })
}

/// Opens a dialog and fills its fields. The name field starts with the dialog's initial text.
fn open_dialog(ui: &AppWindow, kind: DialogKind) {
    let text = kind.initial_text();
    let presets = UI_STATE.with(|state| state.borrow().presets.clone());
    let check = presets_view::check_dialog(&kind, &text, &presets);

    ui.set_dialog_title(SharedString::from(kind.title()));
    ui.set_dialog_ok_text(SharedString::from(kind.ok_label()));
    ui.set_dialog_text(SharedString::from(text));
    ui.set_dialog_error(SharedString::from(check.message.unwrap_or_default()));
    ui.set_dialog_ok_enabled(check.ok_enabled);
    ui.set_dialog_kind(if kind.needs_name() {
        PresetDialogKind::Name
    } else {
        PresetDialogKind::Confirm
    });
    UI_STATE.with(|state| state.borrow_mut().dialog = Some(kind));
}

/// Re-validates the open dialog after its text changed.
fn update_dialog_check(ui: &AppWindow, text: &str) {
    let Some((kind, presets)) = UI_STATE.with(|state| {
        let state = state.borrow();
        state
            .dialog
            .clone()
            .map(|kind| (kind, state.presets.clone()))
    }) else {
        return;
    };
    let check = presets_view::check_dialog(&kind, text, &presets);
    ui.set_dialog_error(SharedString::from(check.message.unwrap_or_default()));
    ui.set_dialog_ok_enabled(check.ok_enabled);
}

/// Confirms the open dialog: sends its command when the name is valid, then closes it.
fn confirm_dialog(ui: &AppWindow, commands: &Sender<AppCommand>, text: &str) {
    let Some((kind, presets)) = UI_STATE.with(|state| {
        let state = state.borrow();
        state
            .dialog
            .clone()
            .map(|kind| (kind, state.presets.clone()))
    }) else {
        return;
    };
    if !presets_view::check_dialog(&kind, text, &presets).ok_enabled {
        return;
    }
    close_dialog(ui);
    send(commands, kind.command(text));
}

/// Closes the open dialog without sending anything.
fn close_dialog(ui: &AppWindow) {
    UI_STATE.with(|state| state.borrow_mut().dialog = None);
    ui.set_dialog_kind(PresetDialogKind::None);
}

/// Converts one output popup row to its Slint form. Device rows never are headings.
fn device_row_item(row: DeviceRow) -> PresetRowItem {
    PresetRowItem {
        header: false,
        label: SharedString::from(row.name),
        active: row.active,
    }
}

/// Converts one popup row to its Slint form.
fn row_item(row: PresetRow) -> PresetRowItem {
    match row {
        PresetRow::Heading(title) => PresetRowItem {
            header: true,
            label: SharedString::from(title),
            active: false,
        },
        PresetRow::Item { name, active } => PresetRowItem {
            header: false,
            label: SharedString::from(name),
            active,
        },
    }
}

/// Wraps a vector as a Slint model.
fn model<T: Clone + 'static>(items: Vec<T>) -> ModelRc<T> {
    ModelRc::new(VecModel::from(items))
}

/// Updates `current` in place when it has the same length as `items`, changing only the rows
/// that differ; returns a new model only when the length changed.
///
/// Replacing the model of a `for` repeater re-creates its children. For the band sliders that
/// would cancel a drag in progress every time the controller echoes the new gain back, so the
/// model is kept and edited row by row instead.
fn sync_model<T: Clone + PartialEq + 'static>(
    current: &ModelRc<T>,
    items: Vec<T>,
) -> Option<ModelRc<T>> {
    if current.row_count() != items.len() {
        return Some(model(items));
    }
    for (row, item) in items.into_iter().enumerate() {
        if current.row_data(row).as_ref() != Some(&item) {
            current.set_row_data(row, item);
        }
    }
    None
}
