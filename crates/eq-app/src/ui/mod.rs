//! Slint user interface: window creation, callback wiring and the bridge from controller events.
//!
//! Threads: the Slint event loop runs on the calling (main) thread. A small forwarder thread
//! blocks on the controller's [`AppEvent`] channel and hands each event to the event loop with
//! `slint::invoke_from_event_loop`. UI callbacks turn user actions into [`AppCommand`]s.

